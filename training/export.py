"""Export a trained model for the extension (default: extension/model.js).

Batch norm is folded into the preceding convolution, and weights are stored
as int8 with one float32 scale per output row/channel.
"""

import argparse
import base64
import json
from pathlib import Path

import numpy as np
import torch

from train import Net

OUT = Path(__file__).resolve().parent.parent / "extension" / "model.js"


def fold(conv, bn):
    w = conv.weight.detach().double()
    scale = bn.weight.detach().double() / torch.sqrt(bn.running_var.double() + bn.eps)
    w = w * scale.view(-1, *([1] * (w.dim() - 1)))
    b = bn.bias.detach().double() - bn.running_mean.double() * scale
    return w, b


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("model", help="trained .pt checkpoint")
    ap.add_argument("--out", type=Path, default=OUT, help="output file (default: extension/model.js)")
    args = ap.parse_args()

    net = Net()
    net.load_state_dict(torch.load(args.model, map_location="cpu"))
    net.eval()
    rnn = net.rnn
    layers = {
        "c1": fold(net.c1[0], net.c1[1]),
        "c2": fold(net.c2[0], net.c2[1]),
        "c3": fold(net.c3[0], net.c3[1]),
        "c4": fold(net.c4[0], net.c4[1]),
    }
    # LSTM gates are ordered i, f, g, o; both biases are summed into the input
    # weights' bias, and the recurrent weights have none.
    for name, suffix in (("fwd", ""), ("bwd", "_reverse")):
        w_ih = getattr(rnn, f"weight_ih_l0{suffix}").detach().double()
        w_hh = getattr(rnn, f"weight_hh_l0{suffix}").detach().double()
        b = (getattr(rnn, f"bias_ih_l0{suffix}") + getattr(rnn, f"bias_hh_l0{suffix}")).detach().double()
        layers[f"{name}_ih"] = (w_ih, b)
        layers[f"{name}_hh"] = (w_hh, None)
    layers["out"] = (net.out.weight.detach().double(), net.out.bias.detach().double())
    blob = bytearray()
    specs = []
    for name, (w, b) in layers.items():
        w = w.numpy()
        flat = w.reshape(w.shape[0], -1)
        scale = np.abs(flat).max(1) / 127
        scale[scale == 0] = 1
        q = np.clip(np.round(flat / scale[:, None]), -127, 127).astype(np.int8)
        spec = {"name": name, "shape": list(w.shape)}
        spec["offset"] = len(blob)
        blob += q.tobytes()
        while len(blob) % 4:
            blob += b"\0"
        spec["scaleOffset"] = len(blob)
        blob += scale.astype("<f4").tobytes()
        if b is not None:
            spec["biasOffset"] = len(blob)
            blob += b.numpy().astype("<f4").tobytes()
        specs.append(spec)
    model = {"layers": specs, "data": base64.b64encode(bytes(blob)).decode()}
    args.out.write_text(
        "// Generated by training/export.py. Do not edit.\n"
        f"var AIUB_CAPTCHA_MODEL = {json.dumps(model)};\n"
    )
    print(f"wrote {args.out} ({args.out.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
